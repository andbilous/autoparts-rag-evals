CAP = ParagraphStyle("c", fontName="Arial", fontSize=9.5, leading=12, spaceAfter=8)
CELL = ParagraphStyle("cell", fontName="Arial", fontSize=9, leading=11)
CELL_H = ParagraphStyle("cellh", fontName="Arial-Bold", fontSize=9, leading=11)


class Figure(Flowable):
    """Порожня рамка, що імітує схему."""

    def __init__(self, label: str, height: float = 45 * mm):
        super().__init__()
        self.label = label
        self.height = height
        self.width = 120 * mm

    def wrap(self, *_):
        return self.width, self.height

    def draw(self):
        c = self.canv
        c.setStrokeColor(colors.grey)
        c.rect(0, 0, self.width, self.height)
        c.line(0, 0, self.width, self.height)
        c.line(0, self.height, self.width, 0)
        c.setFont("Arial", 8)
        c.drawString(4, 4, self.label)


def table(rows: list[list[str]]) -> Table:
    data = [[Paragraph(c, CELL_H) for c in rows[0]]] + [
        [Paragraph(c, CELL) for c in r] for r in rows[1:]
    ]
    t = Table(data, repeatRows=1, hAlign="LEFT")
    t.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e6e6e6")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )
    return t


def build(path: Path, header: str, story: list) -> None:
    def on_page(canvas, doc):
        canvas.saveState()
        canvas.setFont("Arial", 8)
        canvas.drawString(20 * mm, A4[1] - 12 * mm, header)
        canvas.drawRightString(A4[0] - 20 * mm, 10 * mm, f"Сторінка {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(
        str(path), pagesize=A4, topMargin=20 * mm, bottomMargin=20 * mm,
        leftMargin=20 * mm, rightMargin=20 * mm, title=path.stem,
    )
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)


def p(text: str) -> Paragraph:
    return Paragraph(text, P)


def h(text: str) -> Paragraph:
    return Paragraph(text, H)


