def rasterize(path: Path, dpi: int = 200) -> None:
    """Перетворює PDF на скан: кожна сторінка стає зображенням без текстового шару."""
    src = fitz.open(path)
    dst = fitz.open()
    for page in src:
        pix = page.get_pixmap(dpi=dpi, colorspace=fitz.csGRAY)
        new = dst.new_page(width=page.rect.width, height=page.rect.height)
        new.insert_image(new.rect, pixmap=pix)
    src.close()
    dst.save(path)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = []
    for d in DOCS:
        path = OUT / d["file"]
        header = f"{d['manufacturer']} · Технічна документація"
        build(path, header, d["builder"]())
        if d.get("scan"):
            rasterize(path)
        manifest.append({k: v for k, v in d.items() if k not in ("builder", "scan")})
        print(f"{path.name}: {fitz.open(path).page_count} стор.")
    (OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2))


